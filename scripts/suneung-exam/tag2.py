def score(rules, text):
    return {k: sum(text.count(x) * w for x, w in v) for k, v in rules.items()}
def tag(kind, text):
    sc = score(RULES[kind], text)
    best = sorted(sc, key=lambda k: -sc[k])
    top = best[0]
    conf = 'hi' if sc[top] > 0 and sc[top] >= (sc[best[1]] * 1.6 if len(best) > 1 else 0) else 'lo'
    return top, conf, sc
