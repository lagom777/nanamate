def tag(sub,text):
    sc={}
    for k,v in RULES[sub].items():
        if isinstance(v[0],list) and v[0] and isinstance(v[0][0],tuple):
            sc[k]=sum(text.count(x)*w for x,w in v[0])
        else:
            kws,w=v; sc[k]=sum(text.count(x)*w for x in kws)
    best=sorted(sc,key=lambda k:(-sc[k],PRI[sub].index(k)))
    top=best[0]; conf='hi' if sc[top]>0 and (len(best)<2 or sc[top]>=sc[best[1]]*1.5) else 'lo'
    return top,conf,sc
