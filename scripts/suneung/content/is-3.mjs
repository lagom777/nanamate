<p>감염자 가운데 양성으로 나온 비율은 80 ÷ 100 = 80 %입니다. 비감염자 가운데 음성으로 나온 비율은 882 ÷ 900 = 98 %입니다. 양성으로 나온 98명 가운데 실제 감염자는 80명이므로 80 ÷ 98 ≈ 82 %입니다. 양성 가운데 18명은 감염되지 않은 사람이고, 감염자 20명은 음성으로 나와 놓쳤습니다. 그래서 빠른 검사로 먼저 거르고 정확한 검사로 다시 확인하는 방법을 씁니다.</p>
