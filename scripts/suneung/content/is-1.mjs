<p>섞은 용액의 액성은 H<sup>+</sup>과 OH<sup>−</sup>의 개수를 비교하면 정해집니다. 1 : 1로 반응하므로 적은 쪽이 모두 쓰이고, 많은 쪽이 남습니다.</p>
