<h2>3. 주기율표와 전자 배치</h2>
<p><strong>주기율표</strong>는 원소를 원자 번호 순으로 늘어놓되, 성질이 비슷한 원소가 같은 세로줄에 오도록 배열한 표입니다. 원자 번호는 원자핵 속 양성자 수이고, 원자에서는 전자 수와 같습니다.</p>
<ul>
<li><strong>주기</strong>: 가로줄입니다. 같은 주기의 원소는 전자가 들어 있는 전자껍질 수가 같습니다.</li>
<li><strong>족</strong>: 세로줄입니다. 같은 족의 원소는 가장 바깥 전자껍질의 전자 수가 같아서 화학적 성질이 비슷합니다.</li>
</ul>
