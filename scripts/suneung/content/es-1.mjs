<p>1년에 4 cm씩 멀어지는 두 판은 1억 년 동안 4 cm/년 × 10<sup>8</sup> 년 = 4×10<sup>8</sup> cm = 4000 km 멀어집니다. 같은 계산을 단위 변환으로 하면 4 cm/년 = 40 km/백만 년이고, 1억 년은 100백만 년이므로 40 × 100 = 4000 km입니다.</p>

