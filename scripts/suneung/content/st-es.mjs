<p>편차 자료는 값에서 평균을 뺀 것입니다. 양수이면 평균보다 높고, 음수이면 평균보다 낮습니다. 편차의 0을 기온 0°C로 읽지 않습니다. 범례에 편차라고 있으면 부호부터 표시합니다. 복사 평형 그림은 흡수와 방출의 화살표를 구분하고, 같은 단위일 때만 합을 비교합니다. 반사로 나간 화살표를 흡수에 더하지 않습니다. 온실 효과는 대기가 태양 빛을 모두 가두는 그림이 아니라, 지표가 방출한 적외선의 일부를 대기가 흡수하고 다시 지표 쪽으로 보내는 그림으로 읽습니다.</p>
