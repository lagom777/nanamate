<h3>양자수 표</h3>
<ol>
<li>n이 자연수인지, l이 0 이상 n−1 이하인지, m<sub>l</sub>이 −l 이상 +l 이하인지, m<sub>s</sub>가 ±1/2인지 한 줄씩 검사합니다. 하나라도 벗어나면 그 전자는 존재하지 않습니다.</li>
