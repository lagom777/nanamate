<p>몰 농도는 용액 1 L 속에 용질이 몇 몰 있는지를 나타냅니다. mol/L라고 쓰며 M으로 줄여 쓰기도 합니다. 부피의 기준은 용매가 아니라 용액입니다. 질량 퍼센트는 용액 전체 질량 중 용질 질량의 백분율입니다. 액체끼리의 부피 퍼센트는 섞을 때 부피가 합과 달라질 수 있어, 이 노트에서는 질량 퍼센트와 몰 농도를 계산의 기본으로 둡니다. 문제에서 혼합 후의 부피를 따로 주면 그 값을 씁니다.</p>
