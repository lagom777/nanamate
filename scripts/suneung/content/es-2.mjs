<p>진로의 오른쪽 관측소는 태풍이 남쪽에서 다가올 때 동풍, 중심이 서쪽에 있을 때 남풍, 중심이 북쪽으로 지나간 뒤 서풍이 되어 풍향이 시계 방향으로 바뀝니다. 왼쪽 관측소는 동풍에서 북풍으로 바뀌어 시계 반대입니다. 기압은 중심이 가장 가까울 때 최저입니다. 눈이 관측소 위를 지나면 바람이 잠시 약해졌다가 눈벽에서 다시 강해집니다.</p>
