<p>포화 용액의 농도가 일정한 것은 용해가 멈춰서가 아닙니다. 녹는 양과 석출되는 양이 같습니다. 같은 온도에서 고체를 더 넣으면 바닥의 고체 양만 늘고, 녹아 있는 농도는 그대로입니다.</p>
