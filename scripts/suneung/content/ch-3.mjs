<li><strong>새 평형과 원래 평형, 조작 직후를 비교.</strong> 물질을 넣은 경우 그 물질의 새 농도는 직후보다 낮고 원래보다는 높습니다. 부피를 줄인 경우 몰수 변화와 농도 변화가 반대 방향일 수 있습니다.</li>
