<p>조각 예시: x&lt;1에서 f(x)=x²+ax+b, x≥1에서 f(x)=3x−1이고 x=1에서 미분가능하려면, 연속으로 1+a+b=2, 즉 a+b=1이고, 도함수 2+a=3이므로 a=1, b=0입니다. 왼쪽 도함수 2x+a는 x=1에서 3, 오른쪽 도함수는 3입니다.</p>
