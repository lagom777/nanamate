/* 작품 상자 — 고어 원문(줄마다 현대어) → 쓰인 고어 표 → 읽는 맛.
   rows: [[원문 줄, 현대어 줄], …] ("" 은 연 구분). words: 고어 사전(anthology-words.mjs)의 낱말 또는 [한자·낱말, 뜻, 풀이]. */
export const poems = []; // 원전 대조용으로 내보낸다
const used = new Map(); // 고어 → 나온 작품들 (고어 총정리용)

const poem = (o) => {
  poems.push(o);
  const short = o.s || o.t;
  const words = (o.words || []).map((w) => {
    if (typeof w !== "string") return w;
    const d = D[w];
    if (!d) throw new Error("고어 사전에 없는 낱말: " + w + " (" + o.t + ")");
    if (!used.has(w)) used.set(w, []);
    if (!used.get(w).includes(short)) used.get(w).push(short);
    return [w, d[0], d[1]];
  });
  const lines = o.rows
    .map(([a, b]) => (a === "" ? `<div class="pb"></div>` : `<div class="pl"><span class="po">${a}</span>${b ? `<span class="pm">${b}</span>` : ""}</div>`))
    .join("");
  const table = words.length
    ? `<details class="poem-w" open><summary>${o.hanja ? "한자 풀이" : "고어 풀이"} · ${words.length}개</summary><div class="wt-wrap"><table class="wt"><thead><tr><th>${o.hanja ? "한자" : "고어"}</th><th>${o.hanja ? "뜻" : "현대어"}</th><th>풀이</th></tr></thead><tbody>${words
        .map((w) => `<tr><td class="w-o">${w[0]}</td><td>${w[1]}</td><td>${w[2] || ""}</td></tr>`)
        .join("")}</tbody></table></div></details>`
    : "";
  return `<div class="poem"><div class="poem-h"><b>${o.t}</b><span>${o.m}</span></div>${o.pre || ""}<div class="poem-t">${lines}</div>${table}<p class="poem-r">${o.taste}</p></div>`;
};

